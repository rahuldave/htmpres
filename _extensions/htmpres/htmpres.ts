function slideInsertCommand(args: string[]) {
  const [deckArg] = positionalArgs(args);
  if (!deckArg) throw new Error("slide insert requires a deck path.");
  const deckPath = resolveDeckFile(deckArg);
  const doc = readSourceDeck(deckPath);
  const before = numericOption(args, "--before");
  const after = numericOption(args, "--after");
  if ((before == null && after == null) || (before != null && after != null)) {
    throw new Error("slide insert requires exactly one of --before <n> or --after <n>.");
  }
  const kind = optionValue(args, "--kind", "text");
  if (!slideKindCatalog.includes(kind)) {
    throw new Error(`Unknown slide kind: ${kind}. Expected one of: ${slideKindCatalog.join(", ")}`);
  }
  const title = optionValue(args, "--title", humanTitle(kind));
  const section = optionValue(args, "--section", "Draft");
  const template = normalizeSlideSource(slideTemplate(kind, { title, section }));
  const targetIndex = before ?? after;
  if (targetIndex == null) throw new Error("Missing slide target.");
  const target = requireSlide(doc, targetIndex);
  const insertAt = before != null
    ? target.start
    : target.index < doc.slides.length
    ? doc.slides[target.index].start
    : doc.text.length;
  // An implicit opening slide needs an explicit boundary when another slide
  // is inserted before it; otherwise its body would join the inserted slide.
  const following = doc.slides.find(slide => slide.start === insertAt);
  const needsBoundary = following && slideSegments(following.raw, { frontMatter: false })[0]?.boundary === "implicit";
  const nextText = insertSourceAt(doc.text, insertAt, template + (needsBoundary ? "\n---\n" : ""));
  Deno.writeTextFileSync(deckPath, nextText);
  console.log(`Inserted ${kind} slide ${before != null ? "before" : "after"} ${targetIndex} in ${relativePath(root, deckPath)}`);
}

async function slideReplaceCommand(args: string[]) {
  const [deckArg, indexArg] = positionalArgs(args);
  const from = optionValue(args, "--from", "");
  if (!deckArg || !indexArg || !from) throw new Error("slide replace requires a deck path, slide number, and --from <slide.qmd>.");
  const deckPath = resolveDeckFile(deckArg);
  const doc = readSourceDeck(deckPath);
  const slide = requireSlide(doc, Number(indexArg));
  const source = from === "-" ? await readStdinText() : Deno.readTextFileSync(resolvePath(root, from));
  let replacement = normalizeSlideSource(source);
  const replacementDoc = parseSourceDeck(replacement);
  if (replacementDoc.slides.length !== 1) {
    throw new Error(`Replacement source must contain exactly one slide (--- or ##); found ${replacementDoc.slides.length}.`);
  }
  if (slideSegments(replacement, { frontMatter: false })[0]?.boundary === "implicit") {
    replacement = normalizeSlideSource(`---\n${source.trim()}`);
  }
  const nextText = doc.text.slice(0, slide.start) + replacement + doc.text.slice(slide.end);
  Deno.writeTextFileSync(deckPath, nextText);
  console.log(`Replaced slide ${slide.index} in ${relativePath(root, deckPath)}`);
}

