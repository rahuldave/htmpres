function extractThemeBlock(css: string, name: string) {
  const selector = `html[data-theme="${name}"]`;
  const selectorIndex = css.indexOf(selector);
  if (selectorIndex < 0) throw new Error(`Unknown theme seed: ${name}`);
  const paragraphStart = css.lastIndexOf("\n\n", selectorIndex);
  const blockStart = paragraphStart < 0 ? 0 : paragraphStart + 2;
  const open = css.indexOf("{", selectorIndex);
  if (open < 0) throw new Error(`Theme block has no opening brace: ${name}`);
  let depth = 0;
  for (let index = open; index < css.length; index += 1) {
    if (css[index] === "{") depth += 1;
    if (css[index] === "}") {
      depth -= 1;
      if (depth === 0) return css.slice(blockStart, index + 1);
    }
  }
  throw new Error(`Theme block has no closing brace: ${name}`);
}

function themeSelectorExists(css: string, name: string) {
  return css.includes(`html[data-theme="${name}"]`) || css.includes(`html[data-theme='${name}']`);
}

function setDeckTheme(text: string, name: string, preserveColorMode = true) {
  const bounds = frontMatterBounds(text);
  if (!bounds.yaml) {
    return `---\ndeck:\n  theme: ${name}\n---\n\n${text}`;
  }
  const lines = bounds.yaml.split(/\r?\n/);
  const deckIndex = lines.findIndex((line) => /^deck:\s*$/.test(line));
  if (deckIndex < 0) {
    lines.push("deck:", `  theme: ${name}`);
  } else {
    let themeIndex = -1;
    let insertIndex = deckIndex + 1;
    for (let index = deckIndex + 1; index < lines.length; index += 1) {
      if (/^\S/.test(lines[index])) break;
      insertIndex = index + 1;
      if (/^\s+theme:\s*/.test(lines[index])) themeIndex = index;
    }
    if (themeIndex >= 0) {
      const indent = lines[themeIndex].match(/^\s*/)?.[0] || "  ";
      let end = themeIndex + 1;
      while (end < lines.length && (!lines[end].trim() || (lines[end].match(/^\s*/)?.[0].length || 0) > indent.length)) end += 1;
      lines.splice(themeIndex, end - themeIndex, `${indent}theme: ${name}`);
    }
    else lines.splice(insertIndex, 0, `  theme: ${name}`);
    if (!preserveColorMode) {
      for (let index = deckIndex + 1; index < lines.length; index += 1) {
        if (/^\S/.test(lines[index])) break;
        if (/^\s+color-mode:\s*/.test(lines[index])) { lines.splice(index, 1); index -= 1; }
      }
    }
  }
  return `${text.slice(0, bounds.start + 4)}${lines.join("\n")}${text.slice(bounds.end)}`;
}

function frontMatterBounds(text: string): FrontMatterBounds {
  if (!text.startsWith("---\n")) return { yaml: "", start: 0, end: 0, bodyStart: 0 };
  const markerStart = text.indexOf("\n---", 4);
  if (markerStart < 0) return { yaml: "", start: 0, end: 0, bodyStart: 0 };
  let markerEnd = markerStart + 4;
  if (text[markerEnd] === "\r" && text[markerEnd + 1] === "\n") markerEnd += 2;
  else if (text[markerEnd] === "\n") markerEnd += 1;
  return {
    yaml: text.slice(4, markerStart),
    start: 0,
    end: markerStart,
    bodyStart: markerEnd,
  };
}

function sourceLines(text: string) {
  const lines: { raw: string; text: string; start: number; end: number; number: number }[] = [];
  let start = 0;
  while (start < text.length) {
    const newline = text.indexOf("\n", start);
    const end = newline >= 0 ? newline + 1 : text.length;
    const raw = text.slice(start, end);
    lines.push({
      raw,
      text: raw.replace(/\r?\n$/, ""),
      start,
      end,
      number: lines.length + 1,
    });
    start = end;
  }
  return lines;
}

function lineNumberForOffset(lines: { start: number; end: number; number: number }[], offset: number) {
  for (const line of lines) {
    if (offset >= line.start && offset < line.end) return line.number;
  }
  return lines.length || 1;
}

