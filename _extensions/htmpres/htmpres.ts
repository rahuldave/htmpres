function themeSeedCss(name: string, from: string) {
  validateThemeName(name);
  if (bundledThemes.themes[from]) return themeStyles({ light: from, dark: from, mode: "auto" }, bundledThemes, name);
  if (from === "blank") return blankThemeCss(name);
  const css = readTemplateFile("source.css");
  const block = extractThemeBlock(css, from);
  return block
    .replace(/^:root,\s*/m, "")
    .replace(/html\[data-theme=(["']).*?\1\]/, `html[data-theme="${name}"]`)
    .trimEnd() + "\n";
}

