async function main() {
  const [command = "help", ...args] = Deno.args;
  if (command === "--help" || command === "-h" || command === "help") {
    usage();
    return;
  }

  try {
    switch (command) {
      case "all":
        await convertCommand([]);
        await renderCommand([]);
        await verifyCommand();
        break;
      case "deck":
        await deckCommand(args);
        break;
      case "convert":
      case "import":
        await convertCommand(args);
        break;
      case "render":
        await renderCommand(args);
        break;
      case "serve":
        await serveCommand(args);
        break;
      case "slide":
        await slideCommand(args);
        break;
      case "theme":
        await themeCommand(args);
        break;
      case "lint":
        await lintCommand(args);
        break;
      case "verify":
        await verifyCommand(args);
        break;
      case "workspace":
        workspaceCommand(args);
        break;
      default:
        console.error(`Unknown command: ${command}\n`);
        usage();
        Deno.exit(1);
    }
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    Deno.exit(1);
  }
}

